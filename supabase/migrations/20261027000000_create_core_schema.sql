create table if not exists public.kiosks (
  id uuid primary key default gen_random_uuid(),
  kiosk_code text not null unique,
  kiosk_name text not null,
  password text not null,
  package_type text not null default 'FREE',
  location text,
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.app_config (
  id bigint generated by default as identity primary key,
  price integer not null default 50000 check (price >= 0),
  qris_time integer not null default 180 check (qris_time between 1 and 300),
  qris_image_url text not null default 'https://placehold.co/300x300?text=QRIS+Belum+Ada',
  video_url text not null default '',
  updated_at timestamptz not null default now()
);

insert into public.app_config (price, qris_time)
values (50000, 180)
on conflict do nothing;

insert into storage.buckets (id, name, public, file_size_limit)
values
  ('qris-images', 'qris-images', true, 52428800),
  ('kiosk-videos', 'kiosk-videos', true, 52428800)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit;
